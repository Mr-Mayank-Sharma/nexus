#!/usr/bin/env python3
"""
Generates the Nexus core schema (PostgreSQL and MySQL) and JPA entities from scripts/core_model_spec.py.

    python3 scripts/gen_core_model.py            # write files; refuses to change a released migration
    python3 scripts/gen_core_model.py --check    # exit 1 if any generated file is out of date (used by tests/CI)

Released migrations are immutable: if regenerating would change an existing V<n> file, the run stops. Add a new
migration in the spec instead.
"""
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(ROOT, "scripts"))
from core_model_spec import ENTITIES, MIGRATIONS  # noqa: E402
from core_seed_spec import SEED, SEED_MIGRATIONS  # noqa: E402

BACKEND = os.path.join(ROOT, "nexus-oms-backend")
RES = os.path.join(BACKEND, "src/main/resources/db/core")
JAVA = os.path.join(BACKEND, "src/main/java/com/nexus/core/model")
HEADER_SQL = "-- Generated by scripts/gen_core_model.py from scripts/core_model_spec.py. Do not edit.\n"
HEADER_JAVA = "// Generated by scripts/gen_core_model.py from scripts/core_model_spec.py. Do not edit.\n"

# OFBiz/Moqui type -> (postgresql, mysql, java type, extra JPA annotation)
TYPE_MAP = {
    "id": ("VARCHAR(40)", "VARCHAR(40)", "String", None),
    "id-long": ("VARCHAR(255)", "VARCHAR(255)", "String", None),
    "indicator": ("CHAR(1)", "CHAR(1)", "Boolean", "@Convert(converter = YesNoConverter.class)"),
    "text-short": ("VARCHAR(63)", "VARCHAR(63)", "String", None),
    "text-medium": ("VARCHAR(255)", "VARCHAR(255)", "String", None),
    "text-intermediate": ("VARCHAR(1023)", "VARCHAR(1023)", "String", None),
    "text-long": ("VARCHAR(4000)", "VARCHAR(4000)", "String", None),
    "text-very-long": ("TEXT", "LONGTEXT", "String", None),  # bound as VARCHAR: pgjdbc rejects null LONG32VARCHAR
    "date-time": ("TIMESTAMP(3)", "DATETIME(3)", "LocalDateTime", None),
    "date": ("DATE", "DATE", "LocalDate", None),
    "time": ("TIME", "TIME", "LocalTime", None),
    "currency-amount": ("NUMERIC(24,4)", "DECIMAL(24,4)", "BigDecimal", None),
    "currency-precise": ("NUMERIC(25,5)", "DECIMAL(25,5)", "BigDecimal", None),
    "number-decimal": ("NUMERIC(26,6)", "DECIMAL(26,6)", "BigDecimal", None),
    "number-integer": ("BIGINT", "BIGINT", "Long", None),
    "number-float": ("DOUBLE PRECISION", "DOUBLE", "Double", None),
}
STAMPS = ["lastUpdatedStamp", "lastUpdatedTxStamp", "createdStamp", "createdTxStamp"]


def snake(name):
    return re.sub(r"(?<=[a-z0-9])([A-Z])", r"_\1", name).lower()


BY_NAME = {e["name"]: e for e in ENTITIES}


def pk_fields(e):
    return [f for f in e["fields"] if "pk" in f[2]]


def fk_target(e, field):
    for opt in field[2]:
        if isinstance(opt, tuple) and opt[0] == "fk":
            target = BY_NAME[opt[1]]
            tfield = opt[2] or field[0]
            if tfield not in [f[0] for f in pk_fields(target)]:
                raise SystemExit(f"{e['name']}.{field[0]}: FK target {opt[1]}.{tfield} is not its primary key")
            if len(pk_fields(target)) != 1:
                raise SystemExit(f"{e['name']}.{field[0]}: FK to {opt[1]}, which has a composite key; reference all key fields")
            return target, tfield
    return None


def added_in(f):
    """The migration a field was added in, or None for a field of the table's first version."""
    for opt in f[2]:
        if isinstance(opt, tuple) and opt[0] == "added":
            if "required" in f[2] or "pk" in f[2]:
                raise SystemExit(f"{f[0]}: a column added later must be nullable and not part of the key")
            return opt[1]
    return None


def short(name, limit=60):
    """Constraint names: unique, at most 60 characters (MySQL allows 64)."""
    if len(name) <= limit:
        return name
    import hashlib
    h = hashlib.sha1(name.encode()).hexdigest()[:8]
    return name[: limit - 9] + "_" + h


def ddl(e, vendor):
    t = snake(e["name"])
    col = 0 if vendor == "postgresql" else 1
    lines = []
    for f in e["fields"]:
        if added_in(f) is not None:
            continue   # added by its own migration
        sqltype = TYPE_MAP[f[1]][col]
        notnull = " NOT NULL" if ("pk" in f[2] or "required" in f[2]) else ""
        lines.append(f"    {snake(f[0])} {sqltype}{notnull}")
    ts = "TIMESTAMP(3)" if vendor == "postgresql" else "DATETIME(3)"
    for s in STAMPS:
        lines.append(f"    {snake(s)} {ts} NOT NULL DEFAULT CURRENT_TIMESTAMP(3)")
    lines.append(f"    CONSTRAINT {short('pk_' + t)} PRIMARY KEY ({', '.join(snake(f[0]) for f in pk_fields(e))})")
    for f in e["fields"]:
        if "unique" in f[2]:
            lines.append(f"    CONSTRAINT {short('uk_' + t + '_' + snake(f[0]))} UNIQUE ({snake(f[0])})")
    tail = ";" if vendor == "postgresql" else " ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_bin;"
    out = [f"CREATE TABLE {t} (\n" + ",\n".join(lines) + f"\n){tail}"]
    for i, idx in enumerate(e["indexes"], 1):
        out.append(f"CREATE INDEX {short('ix_' + t + '_' + str(i))} ON {t} ({', '.join(snake(c) for c in idx)});")
    return out


def fks(e, only=None):
    """Foreign keys of the table's first version, or (only=[fields]) of the given added fields."""
    t = snake(e["name"])
    out = []
    for f in e["fields"]:
        if only is None and added_in(f) is not None:
            continue
        if only is not None and f[0] not in only:
            continue
        tgt = fk_target(e, f)
        if tgt:
            target, tfield = tgt
            name = short(f"fk_{t}_{snake(f[0])}")
            out.append(f"ALTER TABLE {t} ADD CONSTRAINT {name} FOREIGN KEY ({snake(f[0])}) "
                       f"REFERENCES {snake(target['name'])} ({snake(tfield)});")
            # MySQL indexes FK columns itself; PostgreSQL does not, so add one unless the column leads the PK.
            pkcols = [p[0] for p in pk_fields(e)]
            if not pkcols or pkcols[0] != f[0]:
                out.append(f"--pg-only CREATE INDEX {short('ix_' + t + '_' + snake(f[0]))} ON {t} ({snake(f[0])});")
    return out


def migration_sql(version, name, entity_names, vendor):
    ents = [BY_NAME[n] for n in entity_names]
    parts = [HEADER_SQL, f"-- V{version}: {name} ({vendor})\n"]
    for e in ents:
        parts.append("\n-- " + e["doc"] + "\n")
        parts.append("\n".join(ddl(e, vendor)) + "\n")
    later = [(e, f) for e in ENTITIES for f in e["fields"] if added_in(f) == version]
    if later:
        parts.append("\n-- Columns added to tables released earlier.\n")
        for e, f in later:
            parts.append(f"ALTER TABLE {snake(e['name'])} ADD COLUMN {snake(f[0])} {TYPE_MAP[f[1]][0 if vendor == 'postgresql' else 1]};\n")
    parts.append("\n-- Foreign keys, added after every table exists.\n")
    fk_sets = [(e, None) for e in ents] + [(e, [f[0]]) for e, f in later]
    for e, only in fk_sets:
        for line in fks(e, only):
            if line.startswith("--pg-only "):
                if vendor == "postgresql":
                    parts.append(line[len("--pg-only "):] + "\n")
            else:
                parts.append(line + "\n")
    return "".join(parts)


def sql_value(v):
    if v is None:
        return "NULL"
    if isinstance(v, (int, float)) and not isinstance(v, bool):
        return str(v)
    return "'" + str(v).replace("'", "''") + "'"


def seed_sql(version, name, blocks):
    """Plain INSERTs that run unchanged on PostgreSQL and MySQL; stamp columns take their defaults."""
    parts = [HEADER_SQL, f"-- V{version}: {name} (PostgreSQL and MySQL)\n"]
    for table, columns, data in blocks:
        parts.append(f"\n-- {table}: {len(data)} row(s)\n")
        for row in data:
            parts.append(f"INSERT INTO {table} ({', '.join(columns)}) VALUES ({', '.join(sql_value(v) for v in row)});\n")
    return "".join(parts)


def java_entity(e):
    pkg = f"com.nexus.core.model.{e['package']}"
    cls = e["name"]
    pks = pk_fields(e)
    composite = len(pks) > 1
    imports = {"jakarta.persistence.Column", "jakarta.persistence.Entity", "jakarta.persistence.Id",
               "jakarta.persistence.Table", "lombok.Getter", "lombok.NoArgsConstructor", "lombok.Setter",
               "com.nexus.core.model.CoreEntity"}
    if composite:
        imports.add("jakarta.persistence.IdClass")
    body = []
    for f in e["fields"]:
        jtype = TYPE_MAP[f[1]][2]
        ann = TYPE_MAP[f[1]][3]
        if jtype in ("LocalDateTime", "LocalDate", "LocalTime"):
            imports.add(f"java.time.{jtype}")
        if jtype == "BigDecimal":
            imports.add("java.math.BigDecimal")
        if ann and "YesNoConverter" in ann:
            imports.update({"jakarta.persistence.Convert", "org.hibernate.type.YesNoConverter"})
        if ann and "JdbcTypeCode" in ann:
            imports.update({"org.hibernate.annotations.JdbcTypeCode", "org.hibernate.type.SqlTypes"})
        lines = []
        if "pk" in f[2]:
            lines.append("    @Id")
        if "audit" in f[2]:
            imports.add("com.nexus.core.audit.AuditedField")
            lines.append("    @AuditedField")
        if ann:
            lines.append(f"    {ann}")
        nullable = ", nullable = false" if ("pk" in f[2] or "required" in f[2]) else ""
        length = re.search(r"\((\d+)\)", TYPE_MAP[f[1]][0])
        length_attr = f", length = {length.group(1)}" if length and jtype == "String" and f[1] != "indicator" else ""
        lines.append(f'    @Column(name = "{snake(f[0])}"{nullable}{length_attr})')
        lines.append(f"    private {jtype} {f[0]};")
        body.append("\n".join(lines))
    idclass = f"@IdClass({cls}.Key.class)\n" if composite else ""
    key = ""
    if composite:
        imports.update({"java.io.Serializable", "lombok.AllArgsConstructor", "lombok.EqualsAndHashCode"})
        kf = "\n".join(f"        private {TYPE_MAP[f[1]][2]} {f[0]};" for f in pks)
        key = ("\n\n    /** Composite primary key. */\n    @Getter @Setter @NoArgsConstructor @AllArgsConstructor @EqualsAndHashCode\n"
               f"    public static class Key implements Serializable {{\n{kf}\n    }}")
    imp = "\n".join(f"import {i};" for i in sorted(imports))
    return (f"{HEADER_JAVA}package {pkg};\n\n{imp}\n\n/** {e['doc']} */\n@Entity\n"
            f'@Table(name = "{snake(cls)}")\n{idclass}@Getter\n@Setter\n@NoArgsConstructor\n'
            f"public class {cls} extends CoreEntity {{\n\n" + "\n\n".join(body) + key + "\n}\n")


def outputs():
    files = {}
    for version, name, ents in MIGRATIONS:
        for vendor in ("postgresql", "mysql"):
            files[os.path.join(RES, vendor, f"V{version}__{name}.sql")] = migration_sql(version, name, ents, vendor)
    for version, name, tables in SEED_MIGRATIONS:
        files[os.path.join(RES, "common", f"V{version}__{name}.sql")] = seed_sql(version, name, tables)
    for e in ENTITIES:
        files[os.path.join(JAVA, e["package"], e["name"] + ".java")] = java_entity(e)
    return files


def main():
    check = "--check" in sys.argv
    released = re.compile(r"/db/core/(postgresql|mysql|common)/V\d+__")
    stale, blocked = [], []
    for path, content in outputs().items():
        old = open(path).read() if os.path.exists(path) else None
        if old == content:
            continue
        stale.append(path)
        if old is not None and released.search(path) and "--allow-unreleased" not in sys.argv:
            blocked.append(path)
    if check:
        for p in stale:
            print("out of date:", os.path.relpath(p, ROOT))
        sys.exit(1 if stale else 0)
    if blocked:
        for p in blocked:
            print("refusing to change a released migration:", os.path.relpath(p, ROOT))
        print("Add a new migration in core_model_spec.MIGRATIONS instead (or pass --allow-unreleased before the first commit).")
        sys.exit(1)
    for path, content in outputs().items():
        os.makedirs(os.path.dirname(path), exist_ok=True)
        with open(path, "w") as f:
            f.write(content)
    print(f"{len(ENTITIES)} entities, {len(MIGRATIONS)} migration(s); {len(stale)} file(s) written")


if __name__ == "__main__":
    main()
